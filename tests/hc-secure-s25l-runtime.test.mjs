import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {createDisposableSecurityRuntime} from './security-runtime/disposableRuntime.mjs';
test('isolated actual HTTP runtime: personas, bypass, durable mutation and receipt',async()=>{
 const dir=mkdtempSync('/tmp/hc-secure-s25l-'),filename=dir+'/test.sqlite';
 let now=Date.now(),r=createDisposableSecurityRuntime({testOnly:true,filename,clock:()=>now});
 const url=await r.listen();r.seed();
 const call=async(path,token,body,headers={})=>{const res=await fetch(url+path,{method:body===undefined?'GET':'POST',headers:{...(token?{authorization:'Bearer '+token}:{}),...(body===undefined?{}:{'content-type':'application/json'}),...headers},...(body===undefined?{}:{body:JSON.stringify(body)})});return [res.status,await res.json()]};
 const note='/test/notes/sample-1',other='/test/notes/sample-2';
 try{
 const owner=r.provision('101'),manager=r.provision('102'),employee=r.provision('103'),multi=r.provision('104'),restricted=r.provision('105'),revoked=r.provision('107'),expired=r.provision('108',{expired:true}),remote=r.provision('103',{offsite:true,offsiteAllowed:true}),badRemote=r.provision('103',{offsite:true});
 assert.throws(()=>r.provision('106'));
 for(const p of [owner,manager,employee,multi,remote])assert.equal((await call(note,p.token))[0],200);
 for(const p of [restricted,expired,badRemote])assert.equal((await call(note,p.token))[0],403);
 assert.equal((await call(other,multi.token))[0],200);
 assert.equal((await call(other,owner.token))[0],403);
 assert.equal((await call(note,null,undefined,{'x-employee-id':'101','x-role':'owner','x-forwarded-for':'127.0.0.1'}))[0],401);
 assert.equal((await call(note,employee.token+'tampered'))[0],401);
 assert.equal((await call('/test/unknown',owner.token))[0],403);
 assert.equal((await call('/test/login',null,{id:'101'}))[0],401);
 r.revoke(revoked.binding);assert.equal((await call(note,revoked.token))[0],403);
 const approvalRef=r.approve({actor:'102',resource:'sample-1',label:'Changed fictional note',revision:1});
 const body={label:'Changed fictional note',expectedRevision:1,approvalRef,key:'command1'};
 for(const p of [employee,owner,restricted])assert.equal((await call(note,p.token,body))[0],403);
 assert.equal((await call(note,manager.token,{...body,actor:'101'}))[0],400);
 assert.equal((await call(note,manager.token,{...body,label:'substituted'}))[0],403);
 assert.equal((await call(note,manager.token,{...body,approvalRef:'invented'}))[0],403);
 assert.deepEqual(await call(note,manager.token,body),[200,{revision:2,replayed:false}]);
 assert.deepEqual(await call(note,manager.token,body),[200,{revision:2,replayed:true}]);
 assert.equal((await call(note,manager.token,{...body,key:'command2'}))[0],409);
 assert.equal((await call(note,employee.token))[1].label,'Changed fictional note');
 const receipt='/test/receipts/command1';
 assert.equal((await call(receipt,employee.token))[0],403);
 assert.equal((await call(receipt,manager.token))[0],403);
 r.revoke(manager.binding);
 assert.equal((await call(note,manager.token,body))[0],403);
 assert.deepEqual(await call(receipt,owner.token),[200,{revision:2,outcome:'committed',retryAllowed:false}]);
 r.advanceEpoch();assert.equal((await call(note,owner.token))[0],403);
 const current=r.provision('103');assert.equal((await call(note,current.token))[0],200);
 now+=901000;assert.equal((await call(note,current.token))[0],401);
 assert.equal(r.db.prepare('SELECT count(*) n FROM receipt').get().n,1);
 assert.equal(r.db.prepare("SELECT count(*) n FROM audit WHERE outcome='committed'").get().n,1);
 assert.ok(r.db.prepare("SELECT count(*) n FROM audit WHERE outcome='denied'").get().n>0);
 await r.close();r=createDisposableSecurityRuntime({testOnly:true,filename,clock:()=>now});
 assert.equal(r.db.prepare("SELECT revision FROM note WHERE id='sample-1'").get().revision,2);
 assert.equal(r.db.prepare('SELECT count(*) n FROM receipt').get().n,1);
 assert.ok(r.db.prepare('SELECT count(*) n FROM audit').get().n>0);
 }finally{await r.close();rmSync(dir,{recursive:true,force:true})}
});
test('runtime refuses implicit enablement and non-disposable path',()=>{assert.throws(()=>createDisposableSecurityRuntime());assert.throws(()=>createDisposableSecurityRuntime({testOnly:true,filename:'/var/data/production.sqlite'}))});
